-- My Login Form: WordPress users table in Supabase
--
-- Copy this complete file into Supabase Dashboard > SQL Editor > New Query,
-- then click Run. It is safe to run again if the table already exists.
-- The Users > Sync WordPress Users to Supabase action writes to this table
-- using the server-side service_role key and upserts by wp_user_id.

create table if not exists public.my_login_users (
    id              bigint generated by default as identity primary key,
    wp_user_id      bigint not null unique,
    email           text not null unique,
    display_name    text,
    first_name      text,
    last_name       text,
    username        text,
    phone           text,
    country         text,
    city            text,
    address         text,
    social_provider text,
    profile_picture text,
    email_verified  boolean not null default true,
    updated_at      timestamptz not null default now()
);

-- Add fields missing from tables created by older plugin versions.
alter table public.my_login_users add column if not exists wp_user_id      bigint;
alter table public.my_login_users add column if not exists email           text;
alter table public.my_login_users add column if not exists display_name    text;
alter table public.my_login_users add column if not exists first_name      text;
alter table public.my_login_users add column if not exists last_name       text;
alter table public.my_login_users add column if not exists username        text;
alter table public.my_login_users add column if not exists phone           text;
alter table public.my_login_users add column if not exists country         text;
alter table public.my_login_users add column if not exists city            text;
alter table public.my_login_users add column if not exists address         text;
alter table public.my_login_users add column if not exists social_provider text;
alter table public.my_login_users add column if not exists profile_picture text;
alter table public.my_login_users add column if not exists email_verified  boolean not null default true;
alter table public.my_login_users add column if not exists updated_at      timestamptz not null default now();

-- PostgREST uses this unique key when the plugin upserts WordPress accounts.
create unique index if not exists my_login_users_wp_user_id_key
    on public.my_login_users (wp_user_id);
create unique index if not exists my_login_users_email_key
    on public.my_login_users (email);

-- Keep profile data private. The plugin writes server-side with service_role;
-- browser-facing anon/authenticated roles receive no table access.
alter table public.my_login_users enable row level security;
drop policy if exists "Allow anon read" on public.my_login_users;
drop policy if exists "Allow service insert" on public.my_login_users;
drop policy if exists "Allow service update" on public.my_login_users;
drop policy if exists "my_login_users anon insert" on public.my_login_users;
drop policy if exists "my_login_users anon update" on public.my_login_users;
drop policy if exists "my_login_users anon select" on public.my_login_users;
revoke all on table public.my_login_users from anon, authenticated;
grant usage on schema public to service_role;
grant all on table public.my_login_users to service_role;
grant usage, select on sequence public.my_login_users_id_seq to service_role;
